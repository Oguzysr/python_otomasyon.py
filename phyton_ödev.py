from abc import ABC, abstractmethod

# Sınıf Tanımlamaları
class Kaynak(ABC):
    def __init__(self, kitap_isim, kayit_no):
        self._kitap_isim = kitap_isim
        self._kayit_no = kayit_no

    @property
    def kitap_isim(self):
        return self._kitap_isim

    @kitap_isim.setter
    def kitap_isim(self, value):
        self._kitap_isim = value

    @property
    def kayit_no(self):
        return self._kayit_no

    @kayit_no.setter
    def kayit_no(self, value):
        self._kayit_no = value

class Kitap(Kaynak):
    def __init__(self, kitap_isim, kayit_no, yazar, sayfa_sayisi):
        super().__init__(kitap_isim, kayit_no)
        self._yazar = yazar
        self._sayfa_sayisi = sayfa_sayisi

    @property
    def yazar(self):
        return self._yazar

    @yazar.setter
    def yazar(self, value):
        self._yazar = value

    @property
    def sayfa_sayisi(self):
        return self._sayfa_sayisi

    @sayfa_sayisi.setter
    def sayfa_sayisi(self, value):
        self._sayfa_sayisi = value

    def __str__(self):
        return f"[{self.kayit_no}] {self.kitap_isim} - Yazar: {self.yazar}"

class Dergi(Kaynak):
    def __init__(self, kitap_isim, kayit_no, yayin_donemi, sayi_no):
        super().__init__(kitap_isim, kayit_no)
        self._yayin_donemi = yayin_donemi
        self._sayi_no = sayi_no

    @property
    def yayin_donemi(self):
        return self._yayin_donemi

    @yayin_donemi.setter
    def yayin_donemi(self, value):
        self._yayin_donemi = value

    @property
    def sayi_no(self):
        return self._sayi_no

    @sayi_no.setter
    def sayi_no(self, value):
        self._sayi_no = value

    def __str__(self):
        return f"[{self.kayit_no}] {self.kitap_isim} - Dönem: {self.yayin_donemi}, Sayı: {self.sayi_no}"


class Islem(ABC):
    @abstractmethod
    def ekle(self, nesne):
        pass

    @abstractmethod
    def sil(self, kayit_no):
        pass

    @abstractmethod
    def guncelle(self, kayit_no, yeni_yazar, yeni_sayfa):
        pass

    @abstractmethod
    def listele(self):
        pass

# Kitap Fonksiyonları
class KitapIslem(Islem):
    def __init__(self):
        self.kitap_arsivi = []

    def ekle(self, yeni_kitap):
        for kitap in self.kitap_arsivi:
            if kitap.kayit_no == yeni_kitap.kayit_no:
                print(f"=> HATA: {yeni_kitap.kayit_no} numaralı kayıt zaten sistemde mevcut!")
                return

        self.kitap_arsivi.append(yeni_kitap)
        print("=> İşlem Başarılı: Kitap sisteme kaydedildi.")
        print(f"=> Toplam Kitap Sayısı: {len(self.kitap_arsivi)}")

    def sil(self, aranan_no):
        for kitap in self.kitap_arsivi:
            if kitap.kayit_no == aranan_no:
                self.kitap_arsivi.remove(kitap)
                print(f"=> Başarılı: {aranan_no} numaralı kitap silindi.")
                return
        print(f"=> HATA: {aranan_no} numaralı kitap bulunamadı!")

    def guncelle(self, aranan_no, yeni_yazar, yeni_sayfa):
        for kitap in self.kitap_arsivi:
            if kitap.kayit_no == aranan_no:
                kitap.yazar = yeni_yazar
                kitap.sayfa_sayisi = yeni_sayfa
                print("=> Başarılı: Kitap bilgileri güncellendi.")
                return
        print(f"=> HATA: Güncellenecek {aranan_no} numaralı kitap bulunamadı!")

    def listele(self):
        if len(self.kitap_arsivi) == 0:
            print("=> Kayıt bulunamadı.")
        else:
            print("\n--- KÜTÜPHANEDEKİ KİTAPLAR ---")
            for kitap in self.kitap_arsivi:
                print(kitap)
            print(f"=> Toplam Kitap Sayısı: {len(self.kitap_arsivi)}")

